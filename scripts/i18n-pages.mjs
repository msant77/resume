// Generates the Portuguese and Spanish entry pages (v1/pt/, v1/es/)
// from the English page, so each language has its own URL with its text in the
// markup before any script runs. Run by hand after editing v1/index.html or
// a locale file, and commit the output:  node scripts/i18n-pages.mjs
// No bundler, no framework: plain string replacement over our own markup.
// The same generator as the company's other sites.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const root = new URL('../v1/', import.meta.url).pathname;
const PAGES = ['index.html'];
const LOCALES = { 'pt-BR': 'pt', es: 'es' };   // locale -> URL folder
const SITE = 'https://marcosantana.dev/';

const read = (p) => readFileSync(root + p, 'utf8');
const dict = (loc) => JSON.parse(read(`assets/i18n/${loc}.json`));
const get = (d, key) => key.split('.').reduce((v, k) => (v == null ? v : v[k]), d);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escAttr = (s) => esc(s).replace(/"/g, '&quot;');
const HREF = { home: (dir) => `/${dir}/` };

function value(d, key) {
  const v = get(d, key);
  if (typeof v !== 'string') throw new Error(`missing or not a string: ${key}`);
  return v;
}

function localize(src, loc, dir) {
  const d = dict(loc);
  let out = src;
  // text-only elements
  out = out.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)([^<]*)(<\/\2>)/g,
    (m, open, tag, key, _t, close) => open + esc(value(d, key)) + close);
  // trusted markup from our own files
  out = out.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n-html="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g,
    (m, open, tag, key, _t, close) => open + value(d, key) + close);
  // attributes, then locale-aware links
  out = out.replace(/<[a-z][^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/g, (tag, spec) => {
    for (const pair of spec.split(';')) {
      const [attr, key] = pair.split(':').map((x) => x.trim());
      tag = tag.replace(new RegExp(`(\\s${attr}=")[^"]*(")`), `$1${escAttr(value(d, key))}$2`);
    }
    return tag;
  });
  out = out.replace(/<a\b[^>]*\sdata-href="([a-z]+)"[^>]*>/g,
    (tag, name) => tag.replace(/(\shref=")[^"]*(")/, `$1${HREF[name](dir)}$2`));
  out = out.replace(/(<[^>]*\sdata-canonical="([^"]*)"[^>]*>)/g,
    (tag, _t, path) => tag.replace(/((?:href|content)=")[^"]*(")/, `$1${SITE}${dir}/${path}$2`));
  out = out.replace(/data-lang-btn="([^"]+)"([^>]*)aria-pressed="(true|false)"/g,
    (m, l, mid) => `data-lang-btn="${l}"${mid}aria-pressed="${l === loc ? 'true' : 'false'}"`);
  if (!out.includes('<html lang="en">')) throw new Error('expected <html lang="en"> in the source page');
  out = out.replace('<html lang="en">', `<html lang="${loc}" data-locale-preset="${loc}">`);
  return out.replace('<head>\n', '<head>\n<!-- generated by scripts/i18n-pages.mjs from the English page; edit that page and rerun -->\n');
}

for (const page of PAGES) {
  const src = read(page);
  for (const [loc, dir] of Object.entries(LOCALES)) {
    const target = `${root}${dir}/${page}`;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, localize(src, loc, dir));
    console.log(`wrote v1/${dir}/${page}`);
  }
}
